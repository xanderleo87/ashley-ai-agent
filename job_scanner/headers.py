API_HEADERS = {
    "User-Agent": "AshleyAI/1.0",
    "Accept": "application/json",
    "Accept-Language": "en-US,en;q=0.9",
    "Accept-Encoding": "gzip, deflate, br",
    "Connection": "keep-alive",
}


def get_random_browser_headers(referer: Optional[str] = None) -> dict:
    profile = random.choice(BROWSER_PROFILES)
    headers = {k: v for k, v in profile.items() if k != "name"}
    if referer:
        headers["Referer"] = referer
    return headers


def get_api_headers() -> dict:
    return dict(API_HEADERS)


def add_random_delay() -> float:
    base = random.uniform(1.0, 3.0)
    jitter = random.uniform(0, 1.0)
    return base + jitter
